type goldenOperation struct {
	Method      string `json:"method"`
	Name        string `json:"name"`
	Namespace   string `json:"namespace"`
	OperationID string `json:"operation_id"`
	Path        string `json:"path"`
}

type silverOperation struct {
	HTTPMethod string   `json:"http_method"`
	Name       string   `json:"name"`
	Namespace  string   `json:"namespace"`
	Path       string   `json:"path"`
	Provenance string   `json:"provenance"`
	Sources    []string `json:"sources"`
}

type typedSilverMethod struct {
	Namespace string `json:"namespace"`
	Name      string `json:"name"`
}

type generatedOperation struct {
	Method    string
	Name      string
	Namespace string
	Path      string
}

type namespaceGroup struct {
	Namespace  string
	FieldName  string
	StructName string
	Operations []generatedOperation
	Aliases    []generatedAlias
}

type legacyAlias struct {
	LegacyName      string `json:"legacy_name"`
	LegacyNamespace string `json:"legacy_namespace"`
	Surface         string `json:"surface"`
	TargetName      string `json:"target_name"`
	TargetNamespace string `json:"target_namespace"`
}

type legacyAliasBundle struct {
	Aliases []legacyAlias `json:"aliases"`
}

// generatedAlias is a deprecated forwarder from a pre-migration method name to
// the method the new contract moved it to.
type generatedAlias struct {
	Name    string
	Target  string
	Display string
}

type nestedNamespaceGroup struct {
	Namespace string
	FieldName string
	Children  []namespaceGroup
}

var nonIdentifier = regexp.MustCompile(`[^0-9A-Za-z]+`)
var typedSilverMethods map[string]bool

func main() {
	golden := readGolden("testdata/contract/golden_sdk_inventory.json")
	silver := readSilver("testdata/contract/silver_sdk_inventory.json")
	typedSilverMethods = readTypedSilverMethods("data/typed_silver_methods.json")
	aliases := readAliases("data/legacy/aliases.json")

	goldenGroups := groupOperations(golden, "Golden")
	silverGroups := groupOperations(silver, "Silver")
	goldenGroups = attachAliases(goldenGroups, silverGroups, aliases)

	var out bytes.Buffer
	out.WriteString("// Code generated by scripts/generate_wrappers.go; DO NOT EDIT.\n")
	out.WriteString("\npackage incidentiq\n\n")
	out.WriteString("import \"context\"\n\n")
	writeClientFields(&out, goldenGroups)
	writeSilverRoot(&out, silverGroups)
	writeWireFunction(&out, goldenGroups, silverGroups)
	writeInventoryFunctions(&out, golden, silver)

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		_, _ = os.Stderr.Write(out.Bytes())
		fatal("format generated source: %v", err)
	}
	if err := os.WriteFile("generated_wrappers.go", formatted, 0o644); err != nil {
		fatal("write generated_wrappers.go: %v", err)
	}
}

func readTypedSilverMethods(path string) map[string]bool {
	payload, err := os.ReadFile(path)
	if err != nil {
		fatal("read %s: %v", path, err)
	}
	var raw []typedSilverMethod
	if err := json.Unmarshal(payload, &raw); err != nil {
		fatal("parse %s: %v", path, err)
	}
	methods := make(map[string]bool, len(raw))
	for _, method := range raw {
		methods[method.Namespace+"."+method.Name] = true
	}
	return methods
}

func readGolden(path string) []generatedOperation {
	payload, err := os.ReadFile(path)
	if err != nil {
		fatal("read %s: %v", path, err)
	}
	var raw []goldenOperation
	if err := json.Unmarshal(payload, &raw); err != nil {
		fatal("parse %s: %v", path, err)
	}
	ops := make([]generatedOperation, 0, len(raw))
	for _, op := range raw {
		ops = append(ops, generatedOperation{
			Method:    op.Method,
			Name:      op.Name,
			Namespace: op.Namespace,
			Path:      op.Path,
		})
	}
	return ops
}

